// FORGE-OS 5.5 server checks: unit owner name is host-only and capped. Run on a fresh dev server (first seat = host).
const base = (process.argv[2] || "http://localhost:8080") + "/api/forge";
const call = async (b) => { const r = await fetch(base, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(b) }); return { status: r.status, body: await r.json() }; };
let fails = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails++; };
const tag = Date.now().toString(36).slice(-5).toUpperCase();
const E = await call({ op: "enter", callsign: "H" + tag });
if (E.status !== 200) { console.log("FAIL enter: " + E.status + " " + JSON.stringify(E.body) + " (run on a fresh dev server)"); process.exit(1); }
const H = { code: "TABLE", token: E.body.token };
ok(E.body.you && E.body.you.role === "host", "first seat is the host: " + (E.body.you && E.body.you.role));
const E2 = await call({ op: "enter", callsign: "P" + tag });
ok(E2.status === 200, "player seat: " + E2.status);
const P = { code: "TABLE", token: E2.body.token }, pid = E2.body.you.id;
const rev = async (T) => (await call({ op: "poll", ...T, since: -1 })).body;
const push = async (T, extra) => { const v = await rev(T); return call({ op: "push", ...T, baseRevision: v.revision, ...extra }); };
const sheetOf = async (T, uid) => { const v = await rev(T); return ((v.snapshot && v.snapshot.sheets) || []).find((s) => s.uid === uid); };
const hu = "hunit" + tag.toLowerCase() + "01", pu = "punit" + tag.toLowerCase() + "01";
let r = await push(H, { upserts: [{ uid: hu, name: "HOST UNIT", col: 0, hidden: false, closed: false, ownerId: null, d: { id: "H-1", own: "  A  very   long owner name that goes past the cap  " } }] });
let sh = await sheetOf(H, hu);
ok(r.status === 200 && sh && sh.d.own === "A very long owner name that goes past the cap".slice(0, 28).trim() && sh.d.own.length <= 28, "host upsert: owner name trimmed and capped at 28 " + JSON.stringify(sh && sh.d.own));
r = await push(H, { rests: [{ uid: hu, rest: { id: "H-1", own: "KAI" } }] });
sh = await sheetOf(H, hu);
ok(sh && sh.d.own === "KAI", "host rest write sets the owner name " + JSON.stringify(sh && sh.d.own));
r = await push(P, { upserts: [{ uid: pu, name: "PILOT UNIT", col: 0, hidden: false, closed: false, ownerId: pid, d: { id: "P-1", own: "H" + tag } }] });
sh = await sheetOf(H, pu);
ok(r.status === 200 && sh && sh.ownerId === pid && !sh.d.own, "player upsert: owner name dropped (no name claim) " + JSON.stringify(sh && sh.d));
r = await push(P, { rests: [{ uid: pu, rest: { id: "P-1", own: "H" + tag } }] });
sh = await sheetOf(H, pu);
ok(sh && !sh.d.own && sh.d.id === "P-1", "player rest write: owner name ignored, other fields kept " + JSON.stringify(sh && sh.d));
r = await push(H, { rests: [{ uid: pu, rest: { id: "P-1", own: "NAMED" } }] });
r = await push(P, { rests: [{ uid: pu, rest: { id: "P-1b", own: "" } }] });
sh = await sheetOf(H, pu);
ok(sh && sh.d.own === "NAMED" && sh.d.id === "P-1b", "player cannot clear a host-set owner name " + JSON.stringify(sh && sh.d));
console.log(fails ? fails + " FAILED" : "ALL PASS"); process.exit(fails ? 1 : 0);
